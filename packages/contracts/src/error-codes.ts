export type ErrorCode = (typeof ErrorCodes)[keyof typeof ErrorCodes];

export class ContractError extends Error {
  readonly code: ErrorCode;

  constructor(code: ErrorCode, message: string) {
    super(message);
    this.name = "ContractError";
    this.code = code;
  }
}
